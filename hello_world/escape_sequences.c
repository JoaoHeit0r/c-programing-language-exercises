#include <stdio.h>

int main(){
	printf("Hello World!\n");
	//\n quebra de linha, é chamado de escape sequence
	//função printf() usada para printar texto
	printf("I'm learning C");
	return 0;
}

/*
*escape sequence
*começam por uma backslash \ 
*e representam caracteres especiais 
*que não podem ser escritos diretamente
*/


// Escape Sequence |	Description
// \t				Inserts a horizontal tab	
// \\				Inserts a backslash character (\)	
// \"				Inserts a double quote character